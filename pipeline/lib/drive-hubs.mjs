export const MAX_KM = 250;
export function km(aLat, aLng, bLat, bLng) {
  const R = 6371, r = Math.PI / 180, dLa = (bLat - aLat) * r, dLo = (bLng - aLng) * r;
  const x = Math.sin(dLa / 2) ** 2 + Math.cos(aLat * r) * Math.cos(bLat * r) * Math.sin(dLo / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}
