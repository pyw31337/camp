// 공공시설개방 표준데이터에서 ‘수영장’·‘실내 놀이 시설’만 골라 내는 이름 규칙(수집기·빌더 공용).
// 그 데이터는 주민센터 회의실·도서관 자료실·족구장까지 ‘어린이’ 이름을 달고 섞여 있어, 놀이 시설로 보이는 이름만 남긴다.
const NOT_PLACE = /회의실|강의실|동아리|자료실|열람실|시청각|주차장|매점|헬스|다목적실|강당|교실|미디어|문화교실|어울림터/;
export const isPool = (name) => /수영/.test(name ?? "") && !NOT_PLACE.test(name ?? "");
export const isKidsPlay = (name) => {
  const n = String(name ?? "");
  if (NOT_PLACE.test(n) || /족구|풋살|야구|축구|테니스/.test(n)) return false;
  return /장난감도서관|키즈(?!스포츠클럽)|놀이(방|터|마당|시설|공원)|물놀이|유아(놀이|체육|스포츠)|어린이(교통공원|문화센터|교통랜드)|교통공원|모험/.test(n);
};
